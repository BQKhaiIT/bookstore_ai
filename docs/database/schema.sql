-- BOOKSTORE AI - PostgreSQL schema (core database)
-- Version: 1.0 | PostgreSQL 15+
-- 21 business tables: catalog, accounts, commerce, visitor sessions,
-- user behavior, recommendations, chatbot.
--
-- Run once against an EMPTY database:
--   psql -U postgres -d bookstore_ai -v ON_ERROR_STOP=1 -f schema.sql
--
-- For Laravel development, translate this DDL to migrations; do not
-- execute both schema.sql and equivalent CREATE TABLE migrations.
-- Monetary values are integer VND (BIGINT); timestamps are TIMESTAMPTZ.
-- Status enums and names align with bookstore_module1_openapi.yaml.
-- Admin should archive/disable books rather than deleting sold books.

BEGIN;

-- =============================================================
-- 01. ACCOUNTS
-- =============================================================
CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(150) NOT NULL,
    email               VARCHAR(255) NOT NULL UNIQUE,
    password            VARCHAR(255) NOT NULL,
    phone               VARCHAR(20),
    role                VARCHAR(20) NOT NULL DEFAULT 'customer'
                        CHECK (role IN ('customer', 'admin')),
    status              VARCHAR(20) NOT NULL DEFAULT 'active'
                        CHECK (status IN ('active', 'blocked')),
    email_verified_at   TIMESTAMPTZ,
    remember_token      VARCHAR(100),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE user_addresses (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipient_name      VARCHAR(150) NOT NULL,
    phone               VARCHAR(20) NOT NULL,
    province            VARCHAR(120) NOT NULL,
    district            VARCHAR(120) NOT NULL,
    ward                VARCHAR(120) NOT NULL,
    address_line        TEXT NOT NULL,
    is_default          BOOLEAN NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX uq_user_addresses_one_default
    ON user_addresses(user_id) WHERE is_default = TRUE;

-- =============================================================
-- 02. BOOK CATALOG
-- =============================================================
CREATE TABLE publishers (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL UNIQUE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE authors (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL,
    biography           TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE categories (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(150) NOT NULL,
    slug                VARCHAR(170) NOT NULL UNIQUE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE books (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publisher_id        BIGINT REFERENCES publishers(id) ON DELETE SET NULL,
    isbn                VARCHAR(20) UNIQUE,
    title               VARCHAR(255) NOT NULL,
    slug                VARCHAR(300) NOT NULL UNIQUE,
    description         TEXT,
    price               BIGINT NOT NULL CHECK (price >= 0),
    stock_quantity      INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    cover_url           TEXT,
    status              VARCHAR(20) NOT NULL DEFAULT 'draft'
                        CHECK (status IN ('draft', 'published', 'archived')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE book_authors (
    book_id             BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    author_id           BIGINT NOT NULL REFERENCES authors(id) ON DELETE CASCADE,
    PRIMARY KEY (book_id, author_id)
);

CREATE TABLE book_categories (
    book_id             BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    category_id         BIGINT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
    PRIMARY KEY (book_id, category_id)
);

-- =============================================================
-- 03. COMMERCE
-- =============================================================
CREATE TABLE carts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE cart_items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id             BIGINT NOT NULL REFERENCES carts(id) ON DELETE CASCADE,
    book_id             BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
    quantity            INTEGER NOT NULL CHECK (quantity > 0),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (cart_id, book_id)
);

CREATE TABLE wishlists (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    book_id             BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, book_id)
);

CREATE TABLE reviews (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    book_id             BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
    rating              SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment             TEXT,
    status              VARCHAR(20) NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, book_id)
);

CREATE TABLE orders (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                     BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    order_code                  VARCHAR(40) NOT NULL UNIQUE,
    idempotency_key             VARCHAR(100),
    idempotency_request_hash    VARCHAR(64),
    status                      VARCHAR(20) NOT NULL DEFAULT 'pending'
                                CHECK (status IN ('pending', 'confirmed', 'packing',
                                                  'shipping', 'delivered', 'cancelled')),
    subtotal_amount             BIGINT NOT NULL CHECK (subtotal_amount >= 0),
    shipping_fee                BIGINT NOT NULL DEFAULT 0 CHECK (shipping_fee >= 0),
    total_amount                BIGINT NOT NULL CHECK (total_amount >= 0),
    shipping_address_snapshot   JSONB NOT NULL
                                CHECK (jsonb_typeof(shipping_address_snapshot) = 'object'),
    customer_note               TEXT,
    cancelled_at                TIMESTAMPTZ,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_orders_total CHECK (total_amount = subtotal_amount + shipping_fee),
    CONSTRAINT uq_orders_user_idempotency UNIQUE (user_id, idempotency_key)
);

CREATE TABLE order_items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    book_id             BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
    book_title          VARCHAR(255) NOT NULL,
    quantity            INTEGER NOT NULL CHECK (quantity > 0),
    unit_price          BIGINT NOT NULL CHECK (unit_price >= 0),
    subtotal            BIGINT NOT NULL CHECK (subtotal >= 0),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_order_items_subtotal CHECK (subtotal = unit_price * quantity),
    UNIQUE (order_id, book_id)
);

CREATE TABLE payments (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    method                  VARCHAR(20) NOT NULL DEFAULT 'cod'
                            CHECK (method IN ('cod', 'sandbox_online')),
    provider                VARCHAR(30),
    environment             VARCHAR(20),
    invoice_number          VARCHAR(64) UNIQUE,
    amount                  BIGINT NOT NULL CHECK (amount >= 0),
    status                  VARCHAR(20) NOT NULL DEFAULT 'pending'
                            CHECK (status IN ('pending', 'paid', 'failed', 'refunded')),
    transaction_reference   VARCHAR(150),
    metadata                JSONB,
    paid_at                 TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
-- At most one currently-paid payment record per order.
CREATE UNIQUE INDEX uq_payments_one_paid_per_order
    ON payments(order_id) WHERE status = 'paid';

-- =============================================================
-- 04. GUEST SESSIONS & RECOMMENDATION
-- =============================================================
CREATE TABLE visitor_sessions (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id             BIGINT REFERENCES users(id) ON DELETE SET NULL,
    started_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_active_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at          TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_visitor_sessions_expiry CHECK (expires_at > started_at)
);

CREATE TABLE user_behaviors (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT REFERENCES users(id) ON DELETE SET NULL,
    visitor_session_id  UUID REFERENCES visitor_sessions(id) ON DELETE SET NULL,
    book_id             BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
    event_type          VARCHAR(30) NOT NULL
                        CHECK (event_type IN ('view', 'add_to_cart', 'wishlist',
                                              'purchase', 'rating')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
-- The application must attach an authenticated user ID or a validated
-- visitor session ID on event creation. Either may become NULL later
-- when old personal/session identifiers are purged for privacy.

CREATE TABLE recommendation_models (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_type          VARCHAR(30) NOT NULL
                        CHECK (model_type IN ('popularity', 'cbf', 'cf', 'hybrid')),
    version             VARCHAR(80) NOT NULL,
    parameters          JSONB NOT NULL DEFAULT '{}'::JSONB
                        CHECK (jsonb_typeof(parameters) = 'object'),
    metrics             JSONB NOT NULL DEFAULT '{}'::JSONB
                        CHECK (jsonb_typeof(metrics) = 'object'),
    trained_at          TIMESTAMPTZ NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (model_type, version)
);

CREATE TABLE recommendation_results (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id            BIGINT NOT NULL REFERENCES recommendation_models(id) ON DELETE CASCADE,
    user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    book_id             BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
    score               NUMERIC(14, 8) NOT NULL CHECK (score >= 0),
    rank                INTEGER NOT NULL CHECK (rank > 0),
    generated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (model_id, user_id, book_id),
    UNIQUE (model_id, user_id, rank)
);
-- Guest suggestions should be computed from the current visitor session
-- and need not be persisted in recommendation_results.

-- =============================================================
-- 05. GEMINI CHATBOT HISTORY (authenticated conversations)
-- =============================================================
CREATE TABLE conversations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title               VARCHAR(255),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE messages (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id     BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    role                VARCHAR(20) NOT NULL CHECK (role IN ('user', 'assistant', 'tool')),
    content             TEXT NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================
-- INDEXES (unique constraints already create their own indexes)
-- =============================================================
CREATE UNIQUE INDEX uq_users_email_ci   ON users(LOWER(email));
CREATE INDEX idx_addresses_user       ON user_addresses(user_id);
CREATE INDEX idx_books_publisher      ON books(publisher_id);
CREATE INDEX idx_books_status_price   ON books(status, price);
CREATE INDEX idx_books_title          ON books(title);
CREATE INDEX idx_book_authors_author  ON book_authors(author_id, book_id);
CREATE INDEX idx_book_categories_cat  ON book_categories(category_id, book_id);
CREATE INDEX idx_cart_items_book      ON cart_items(book_id);
CREATE INDEX idx_wishlists_book       ON wishlists(book_id);
CREATE INDEX idx_reviews_book_status  ON reviews(book_id, status);
CREATE INDEX idx_orders_user_created  ON orders(user_id, created_at DESC);
CREATE INDEX idx_orders_status_date   ON orders(status, created_at DESC);
CREATE INDEX idx_order_items_book     ON order_items(book_id);
CREATE INDEX idx_payments_order       ON payments(order_id, created_at DESC);
CREATE INDEX idx_sessions_user        ON visitor_sessions(user_id);
CREATE INDEX idx_sessions_expiry      ON visitor_sessions(expires_at);
CREATE INDEX idx_behaviors_user_date  ON user_behaviors(user_id, created_at DESC);
CREATE INDEX idx_behaviors_sess_date  ON user_behaviors(visitor_session_id, created_at DESC);
CREATE INDEX idx_behaviors_book_event ON user_behaviors(book_id, event_type);
CREATE INDEX idx_rcm_results_user     ON recommendation_results(user_id, generated_at DESC);
CREATE INDEX idx_messages_conv_time   ON messages(conversation_id, created_at, id);

COMMIT;
